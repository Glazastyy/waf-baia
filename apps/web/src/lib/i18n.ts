export type MessageKey = keyof (typeof messages)[typeof defaultLocale];

type MessageParameters = Record<string, string | number>;

export function isSupportedLocale(value: string): value is Locale {
  return supportedLocales.some((locale) => locale.code === value);
}

export function resolveLocale(value: string | null | undefined): Locale {
  if (value && isSupportedLocale(value)) {
    return value;
  }

  return defaultLocale;
}

export function translate(locale: Locale, key: MessageKey, parameters: MessageParameters = {}): string {
  const resolvedLocale = resolveLocale(locale);
  const template: string = messages[resolvedLocale][key] ?? messages[defaultLocale][key];

  return Object.entries(parameters).reduce((message, [name, value]) => {
    return message.replaceAll(`{${name}}`, String(value));
  }, template);
}

export function localize(locale: string | null | undefined) {
  const resolvedLocale = resolveLocale(locale);

  return {
    locale: resolvedLocale,
    text: (key: MessageKey, parameters?: MessageParameters) => translate(resolvedLocale, key, parameters)
  };
}
